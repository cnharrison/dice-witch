import { createHash } from "node:crypto";
import { writeFile } from "node:fs/promises";

const UNICODE_VERSION = "16.0.0";
const outputUrl = new URL(
  "../packages/saved-rolls/src/unicode-16.generated.ts",
  import.meta.url,
);
const sources = {
  age: {
    url: `https://www.unicode.org/Public/${UNICODE_VERSION}/ucd/DerivedAge.txt`,
    sha256: "60caa81b99a4dfb0bc5d38440d323073e3f356f46f9ca7869da848cd0715408b",
  },
  normalization: {
    url: `https://www.unicode.org/Public/${UNICODE_VERSION}/ucd/DerivedNormalizationProps.txt`,
    sha256: "4d4c03892dea9146d674b686e495df2d55a28d071ac474041d73518f887abddc",
  },
};

async function download(source) {
  const response = await fetch(source.url);
  if (!response.ok) throw new Error(`Unicode download failed: ${response.status}`);
  const text = await response.text();
  const digest = createHash("sha256").update(text).digest("hex");
  if (digest !== source.sha256) {
    throw new Error(`Unicode source hash mismatch for ${source.url}`);
  }
  return text;
}

function codePointRange(value) {
  const [start, end = start] = value.split("..").map((part) =>
    Number.parseInt(part, 16),
  );
  return [start, end];
}

function assignedRanges(text) {
  const sourceRanges = text
    .split("\n")
    .map((line) => line.split("#", 1)[0].trim())
    .filter(Boolean)
    .map((line) => codePointRange(line.split(";", 1)[0].trim()))
    .sort(([left], [right]) => left - right);
  const ranges = [];
  for (const [start, end] of sourceRanges) {
    const previous = ranges.at(-1);
    if (previous !== undefined && start <= previous[1] + 1) {
      previous[1] = Math.max(previous[1], end);
    } else {
      ranges.push([start, end]);
    }
  }
  return ranges;
}

function nfkcCasefoldMappings(text) {
  const mappings = new Map();
  for (const rawLine of text.split("\n")) {
    const line = rawLine.split("#", 1)[0].trim();
    if (!line || !line.includes("; NFKC_CF;")) continue;
    const [rangeText, , mappingText = ""] = line
      .split(";")
      .map((part) => part.trim());
    const [start, end] = codePointRange(rangeText);
    const replacement = mappingText
      ? String.fromCodePoint(
          ...mappingText.split(/ +/).map((part) => Number.parseInt(part, 16)),
        )
      : "";
    for (let codePoint = start; codePoint <= end; codePoint += 1) {
      mappings.set(codePoint, replacement);
    }
  }
  return mappings;
}

function compactMappings(mappings) {
  const entries = [...mappings.entries()].sort(([left], [right]) => left - right);
  const ranges = [];
  for (let index = 0; index < entries.length; ) {
    const [start, replacement] = entries[index];
    let end = start;
    let next = index + 1;
    while (
      next < entries.length &&
      entries[next][0] === end + 1 &&
      entries[next][1] === replacement
    ) {
      end = entries[next][0];
      next += 1;
    }
    if (end > start) {
      ranges.push([start, end, replacement]);
      index = next;
      continue;
    }

    const replacementPoints = [...replacement].map((value) => value.codePointAt(0));
    const delta = replacementPoints.length === 1 ? replacementPoints[0] - start : null;
    while (delta !== null && next < entries.length) {
      const [codePoint, nextReplacement] = entries[next];
      const nextPoints = [...nextReplacement].map((value) => value.codePointAt(0));
      if (
        codePoint !== end + 1 ||
        nextPoints.length !== 1 ||
        nextPoints[0] - codePoint !== delta
      ) {
        break;
      }
      end = codePoint;
      next += 1;
    }
    ranges.push([start, end, delta ?? replacement]);
    index = next;
  }
  return ranges;
}

function serialize(value) {
  return JSON.stringify(value).replaceAll("],[", "],\n  [");
}

const [ageText, normalizationText] = await Promise.all([
  download(sources.age),
  download(sources.normalization),
]);
const output = `// Generated by tools/generate-saved-roll-unicode.mjs. Do not edit.\n// Unicode ${UNICODE_VERSION}; source SHA-256 values are pinned in the generator.\n\nexport const UNICODE_ASSIGNED_RANGES = ${serialize(assignedRanges(ageText))} as const;\n\nexport const UNICODE_NFKC_CASEFOLD_RANGES = ${serialize(compactMappings(nfkcCasefoldMappings(normalizationText)))} as const;\n`;
await writeFile(outputUrl, output);
